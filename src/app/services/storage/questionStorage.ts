function loadFromStorage(): Question[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_QUESTIONS));
      return INITIAL_QUESTIONS;
    }
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed) || parsed.length === 0) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_QUESTIONS));
      return INITIAL_QUESTIONS;
    }
    // Filter to ensure only questions for DS-S3IS01 exist
    const filtered = parsed.filter(
      (q) => q.subjectId === "DS-S3IS01" || q.subjectId === "CS201"
    ).map(q => ({ ...q, subjectId: "DS-S3IS01" }));
    if (filtered.length === 0) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_QUESTIONS));
      return INITIAL_QUESTIONS;
    }
    return filtered;
  } catch {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_QUESTIONS));
    return INITIAL_QUESTIONS;
  }
}

function persistToStorage(questions: Question[]): void {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(questions));
}

export function getQuestions(subjectId?: string): Question[] {
  const all = loadFromStorage();
  if (!subjectId) return all;
  return all.filter(
    (q) => q.subjectId.toLowerCase() === subjectId.toLowerCase()
  );
}

export function getQuestionById(id: string): Question | undefined {
  const all = loadFromStorage();
  return all.find((q) => q.id.toLowerCase() === id.toLowerCase());
}

export function addQuestion(
  q: Omit<Question, "id" | "createdAt" | "updatedAt"> & { id?: string }
): Question {
  const all = loadFromStorage();
  const nextId =
    q.id?.trim() ||
    `DS-MANUAL-${String(Math.floor(1000 + Math.random() * 9000))}`;
  const now = new Date().toISOString();

  const newQuestion: Question = {
    ...q,
    id: nextId,
    subjectId: "DS-S3IS01",
    unit: Number(q.unit),
    marks: Number(q.marks),
    createdAt: now,
    updatedAt: now,
  };

  all.push(newQuestion);
  persistToStorage(all);
  return newQuestion;
}

export function updateQuestion(id: string, updates: Partial<Question>): Question | null {
  const all = loadFromStorage();
  const idx = all.findIndex((q) => q.id.toLowerCase() === id.toLowerCase());
  if (idx === -1) return null;

  all[idx] = {
    ...all[idx],
    ...updates,
    unit: updates.unit !== undefined ? Number(updates.unit) : all[idx].unit,
    marks: updates.marks !== undefined ? Number(updates.marks) : all[idx].marks,
    updatedAt: new Date().toISOString(),
  };

  persistToStorage(all);
  return all[idx];
}

export function deleteQuestion(id: string): boolean {
  const all = loadFromStorage();
  const filtered = all.filter((q) => q.id.toLowerCase() !== id.toLowerCase());
  if (filtered.length === all.length) return false;
  persistToStorage(filtered);
  return true;
}

export function importQuestions(
  newQuestions: (Omit<Question, "id" | "createdAt" | "updatedAt"> & { id?: string })[]
): { addedCount: number } {
  const all = loadFromStorage();
  const now = new Date().toISOString();

  let count = 0;
  newQuestions.forEach((q) => {
    const nextId =
      q.id?.trim() ||
      `DS-IMP-${String(Math.floor(1000 + Math.random() * 9000))}`;
    all.push({
      ...q,
      id: nextId,
      subjectId: "DS-S3IS01",
      unit: Number(q.unit),
      marks: Number(q.marks),
      createdAt: now,
      updatedAt: now,
    });
    count++;
  });

  persistToStorage(all);
  return { addedCount: count };
}
